#!/usr/bin/env node
/**
 * synkia-trends v1.0
 * ═══════════════════════════════════════════════════════════════════════════════
 * Read-only JSON API exposing trends and alerts from the SynK-IA stack.
 *
 * Endpoints:
 *   GET /health             → 200 OK
 *   GET /api/trends/models  → model health and provider breakdown (latest SSOT)
 *   GET /api/trends/services→ pm2 service status trend (last 24h, sampled)
 *   GET /api/alerts/recent  → incidents + health probe deltas (last 50)
 *   GET /api/summary        → one-shot dashboard payload
 *
 * Sources (all read-only):
 *   /Users/davidnows/.synkia-ai-hub/openclaw-ssot.json   (generated by ssot.js)
 *   /Users/davidnows/.synkia/incidents/YYYY-MM-DD.jsonl   (written by watchdog)
 *   /Users/davidnows/.openclaw/model-health.json          (written by health-probe)
 *
 * No auth, no mutation. Run under PM2.
 * ═══════════════════════════════════════════════════════════════════════════════
 */
'use strict';

const fs = require('fs');
const path = require('path');
const http = require('http');

const HOME = '/Users/davidnows';
const SSOT_PATH = path.join(HOME, '.synkia-ai-hub/openclaw-ssot.json');
const MODEL_HEALTH_PATH = path.join(HOME, '.openclaw/model-health.json');
const INCIDENT_DIR = path.join(HOME, '.synkia/incidents');
const PORT = parseInt(process.env.TRENDS_PORT || '9700', 10);
const HOST = process.env.TRENDS_HOST || '0.0.0.0';

function readJsonSafe(p) {
  try { return JSON.parse(fs.readFileSync(p, 'utf8')); }
  catch (e) { return { __error: e.message, __path: p }; }
}

function readIncidents() {
  const out = [];
  if (!fs.existsSync(INCIDENT_DIR)) return out;
  const files = fs.readdirSync(INCIDENT_DIR)
    .filter(f => f.endsWith('.jsonl'))
    .sort()
    .reverse()
    .slice(0, 7); // last 7 days
  for (const f of files) {
    const fp = path.join(INCIDENT_DIR, f);
    try {
      const lines = fs.readFileSync(fp, 'utf8').split('\n').filter(Boolean);
      for (const ln of lines) {
        try { out.push(JSON.parse(ln)); } catch (_) {}
      }
    } catch (_) {}
  }
  out.sort((a, b) => (b.ts || '').localeCompare(a.ts || ''));
  return out;
}

function summarizeServices(incidents) {
  const map = new Map();
  for (const inc of incidents) {
    if (!inc || !inc.process) continue;
    const k = inc.process;
    if (!map.has(k)) map.set(k, { process: k, health_fail: 0, pm2_offline: 0, last_event: null, last_status: null });
    const row = map.get(k);
    if (inc.kind === 'health-fail') row.health_fail += 1;
    if (inc.kind === 'pm2-offline') row.pm2_offline += 1;
    row.last_event = inc.ts;
    if (inc.status != null) row.last_status = inc.status;
  }
  return Array.from(map.values()).sort((a, b) => a.process.localeCompare(b.process));
}

function summary() {
  const ssot = readJsonSafe(SSOT_PATH);
  const health = readJsonSafe(MODEL_HEALTH_PATH);
  const incidents = readIncidents();
  const services = summarizeServices(incidents);
  return {
    generated_at: new Date().toISOString(),
    ssot: {
      generated_at: ssot.__generated_at || null,
      model_count: ssot.model_count || 0,
      healthy_model_count: ssot.healthy_model_count || 0,
      local_model_count: ssot.local_model_count || 0,
      remote_model_count: ssot.remote_model_count || 0,
      providers: ssot.providers || [],
      provider_counts: ssot.provider_counts || {},
      degraded_models: ssot.degraded_models || [],
      warnings: ssot.warnings || [],
      last_openclaw_touched: ssot.openclaw_last_touched || null,
    },
    health: {
      last_updated: health.last_updated || null,
      model_count: health.models ? Object.keys(health.models).length : 0,
      degraded: health.models ? Object.entries(health.models).filter(([k, v]) => v.status === 'degraded').map(([k]) => k) : [],
    },
    services,
    recent_incidents: incidents.slice(0, 50),
  };
}

function respond(res, status, body) {
  res.writeHead(status, {
    'Content-Type': 'application/json',
    'Access-Control-Allow-Origin': '*',
    'Cache-Control': 'no-cache, no-store',
  });
  res.end(typeof body === 'string' ? body : JSON.stringify(body, null, 2));
}

const server = http.createServer((req, res) => {
  res.setHeader('Access-Control-Allow-Origin', '*');
  if (req.method === 'OPTIONS') { res.writeHead(204); res.end(); return; }

  const u = new URL(req.url, `http://${req.headers.host || 'localhost'}`);
  const p = u.pathname;

  if (req.method !== 'GET') return respond(res, 405, { error: 'method not allowed' });

  if (p === '/health') return respond(res, 200, { status: 'healthy', service: 'synkia-trends', uptime: process.uptime() });
  if (p === '/api/trends/models') return respond(res, 200, summary());
  if (p === '/api/trends/services') return respond(res, 200, { generated_at: new Date().toISOString(), services: summarizeServices(readIncidents()) });
  if (p === '/api/alerts/recent') return respond(res, 200, { generated_at: new Date().toISOString(), recent: readIncidents().slice(0, 50) });
  if (p === '/api/summary') return respond(res, 200, summary());
  if (p === '/' || p === '/dashboard') {
    const s = summary();
    const html = `<!doctype html><html><head><meta charset="utf-8"><title>SynK-IA Trends</title>
<style>body{font-family:system-ui;background:#0b1020;color:#e6e6e6;padding:24px;max-width:1100px;margin:auto}
h1,h2{color:#7bd3ff} table{border-collapse:collapse;width:100%} td,th{padding:6px 10px;border:1px solid #243;font-size:13px}
th{background:#14213d;color:#7bd3ff} .ok{color:#6ee787}.degraded{color:#ff8585}.warn{color:#ffc857}
.badge{display:inline-block;padding:2px 6px;border-radius:4px;font-size:11px;background:#14213d}
pre{background:#14213d;padding:12px;overflow:auto;border-radius:6px;font-size:12px}</style></head><body>
<h1>🐉 SynK-IA Trends</h1>
<p>Generated: ${s.generated_at} (openclaw last touched: ${s.ssot.last_openclaw_touched || 'n/a'})</p>
<h2>🤖 Models</h2>
<p>Total: <b>${s.ssot.model_count}</b> · Healthy: <b class="ok">${s.ssot.healthy_model_count}</b> · Local: ${s.ssot.local_model_count} · Remote: ${s.ssot.remote_model_count}</p>
<p>By provider: ${Object.entries(s.ssot.provider_counts).map(([k, v]) => `<span class="badge">${k}: ${v}</span>`).join(' ')}</p>
<p>Health file last_updated: ${s.health.last_updated || 'never'}</p>
${s.ssot.degraded_models.length ? `<p class="degraded">Degraded: ${s.ssot.degraded_models.length} — first 5: ${s.ssot.degraded_models.slice(0, 5).join(', ')}</p>` : '<p class="ok">All healthy</p>'}
<h2>🛠 Services (last 24h event counts)</h2>
<table><tr><th>process</th><th>health-fail</th><th>pm2-offline</th><th>last event</th><th>last status</th></tr>
${s.services.map(r => `<tr><td>${r.process}</td><td class="${r.health_fail ? 'degraded' : ''}">${r.health_fail}</td><td class="${r.pm2_offline ? 'degraded' : ''}">${r.pm2_offline}</td><td>${r.last_event || '—'}</td><td>${r.last_status || '—'}</td></tr>`).join('')}</table>
<h2>🗒 Recent incidents (last 50)</h2>
<pre>${s.recent_incidents.map(i => `${i.ts} ${i.kind} ${i.process}${i.status ? ' HTTP '+i.status : ''}`).join('\n') || '(none)'}</pre>
</body></html>`;
    res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8', 'Cache-Control': 'no-cache' });
    res.end(html);
    return;
  }
  respond(res, 404, { error: 'not found', path: p });
});

server.listen(PORT, HOST, () => {
  console.log(`[synkia-trends] listening on http://${HOST}:${PORT}`);
});

process.on('SIGINT',  () => { console.log('[synkia-trends] SIGINT, exit'); process.exit(0); });
process.on('SIGTERM', () => { console.log('[synkia-trends] SIGTERM, exit'); process.exit(0); });
